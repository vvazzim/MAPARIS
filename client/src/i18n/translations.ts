export type Language = 'fr' | 'en';

export function detectDefaultLanguage(): Language {
  if (typeof window === 'undefined') return 'fr';
  
  // 1. Priorité au choix manuel sauvegardé par l'utilisateur
  const stored = localStorage.getItem('maparis_lang');
  if (stored === 'fr' || stored === 'en') return stored;

  // 2. Détection du territoire / langue du navigateur
  const navLang = (navigator.language || (navigator as any).userLanguage || '').toLowerCase();
  
  // Territoires et variantes francophones (fr, fr-FR, fr-BE, fr-CA, fr-CH, fr-LU, etc.)
  if (navLang.startsWith('fr')) {
    return 'fr';
  }

  // Tout territoire non-francophone bascule automatiquement en anglais
  return 'en';
}

